const now = new Date();
const daysAgoIso = (days, hours = 10, minutes = 0) => {
  const d = new Date(now.getTime() - days * 86400000);
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
};

const daysAheadIso = (days, hours = 18, minutes = 0) => {
  const d = new Date(now.getTime() + days * 86400000);
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
};

